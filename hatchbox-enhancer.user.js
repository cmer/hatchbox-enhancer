  function toggleProject(key) {
    if (config.expanded[key]) delete config.expanded[key];
    else config.expanded[key] = true;
    save();
    render();
  }

  function toggleGroup(gid) {
    if (config.collapsedGroups[gid]) delete config.collapsedGroups[gid];
    else config.collapsedGroups[gid] = true;
    save();
    render();
  }

  function placeProject(key, gid, beforeKey = null) {
    const list = orderedKeys(gid).filter((k) => k !== key);
    const at = beforeKey ? list.indexOf(beforeKey) : -1;
    if (at < 0) list.push(key); else list.splice(at, 0, key);

    if (groupByRules(key) === gid) delete config.assignments[key];
    else config.assignments[key] = gid;

    for (const id of Object.keys(config.order)) {
      if (id !== gid) config.order[id] = config.order[id].filter((k) => k !== key);
    }
    config.order[gid] = list;
    save();
    render();
  }

  function deleteGroupFrom(cfg, gid) {
    cfg.groups = cfg.groups.filter((g) => g.id !== gid);
    for (const [k, v] of Object.entries(cfg.assignments)) if (v === gid) delete cfg.assignments[k];
    delete cfg.order[gid];
    delete cfg.collapsedGroups[gid];
  }

