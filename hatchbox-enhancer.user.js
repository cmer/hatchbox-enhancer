  function renderProject(p) {
    const collapsed = p.children.length > 0 && !config.expanded[p.key];
    const block = el('div', { class: 'hbo-project', 'data-key': p.key });

    const parentRow = p.parent.row;
    parentRow.classList.add('hbo-row', 'hbo-parent');
    parentRow.classList.toggle('is-collapsed', collapsed);

    parentRow.prepend(el('span', { class: 'hbo-inj hbo-lead' },
      el('button', { type: 'button', class: 'hbo-ibtn hbo-grip', title: 'Drag to reorder', 'aria-label': 'Drag to reorder ' + p.label, 'data-drag': 'project' }, icon('grip')),
      p.children.length
        ? el('button', {
          type: 'button', class: 'hbo-ibtn hbo-chev', 'aria-expanded': String(!collapsed),
          'aria-label': (collapsed ? 'Show' : 'Hide') + ' other environments of ' + p.label,
          onclick: () => toggleProject(p.key),
        }, icon('chevron'))
        : el('span', { style: 'width:24px;flex:none' })));

    if (collapsed) {
      // A compact "+ staging" toggle next to the name. A failing environment gets a red dot in place of the "+".
      const names = p.children.map((c) => (ENV_LABEL[c.env] || c.env).toLowerCase());
      const parts = [];
      p.children.forEach((c, i) => {
        if (i) parts.push(', ');
        if (c.status === 'failed') parts.push(el('span', { class: 'hbo-dot is-failed', 'aria-hidden': 'true' }));
        else if (i === 0) parts.push('+ ');
        parts.push(names[i]);
      });
      const failing = p.children.filter((c) => c.status === 'failed').map((c) => c.name);
      const title = (failing.length ? `Last deploy failed: ${failing.join(', ')}\n` : '') + 'Click to show';
      const toggle = el('button', {
        type: 'button', class: 'hbo-inj hbo-envtoggle', title,
        'aria-label': `Show ${names.join(', ')} for ${p.label}` + (failing.length ? ` (failing: ${failing.join(', ')})` : ''),
        onclick: () => toggleProject(p.key),
      }, parts);
      (nameLink(parentRow)?.parentElement || parentRow).append(toggle);
    }

    // Non-production apps always show their environment, even with nothing folded under them.
    if (p.parent.env !== 'production') insertTags(parentRow, el('span', { class: 'hbo-inj hbo-tags' }, envPill(p.parent.env)));

    parentRow.append(el('button', {
      type: 'button', class: 'hbo-inj hbo-ibtn hbo-more', 'aria-label': 'Options for ' + p.label,
      onclick: (e) => projectMenu(e.currentTarget, p),
    }, icon('more')));
    block.append(parentRow);

    if (p.children.length) {
      const kids = el('div', { class: 'hbo-children' });
      if (collapsed) kids.style.display = 'none';
      p.children.forEach((c, i) => {
        c.row.classList.add('hbo-row', 'hbo-child');
        c.row.prepend(el('span', { class: 'hbo-inj hbo-lead hbo-tree', 'aria-hidden': 'true', text: i === p.children.length - 1 ? '└' : '├' }));
        insertTags(c.row, el('span', { class: 'hbo-inj hbo-tags' }, envPill(c.env)));
        kids.append(c.row);
      });
      block.append(kids);
    }
    return block;
  }

