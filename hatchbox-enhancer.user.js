  function suggestGroups(draft) {
    const taken = (k) => draft.assignments[k] !== undefined || draft.groups.some((g) => g.prefixes.some((p) => matchesPrefix(k, p)));
    const counts = new Map();
    for (const p of S.projects.values()) {
      if (taken(p.key)) continue;
      const seg = p.key.split('-')[0];
      if (seg) counts.set(seg, (counts.get(seg) || 0) + 1);
    }
    const out = [];
    for (const [seg, n] of counts) {
      if (n >= 2) out.push(newGroup(seg.length <= 3 ? seg.toUpperCase() : seg.charAt(0).toUpperCase() + seg.slice(1), [seg + '-']));
    }
    return out;
  }

