  let menuEl = null;

  function closeMenu() {
    if (!menuEl) return;
    menuEl.remove();
    menuEl = null;
    document.removeEventListener('pointerdown', onMenuOutside, true);
    document.removeEventListener('keydown', onMenuKey, true);
    window.removeEventListener('scroll', closeMenu, true);
    window.removeEventListener('resize', closeMenu);
  }

  function onMenuOutside(e) { if (menuEl && !menuEl.contains(e.target)) closeMenu(); }
  function onMenuKey(e) { if (e.key === 'Escape') { e.stopPropagation(); closeMenu(); } }

  function openMenu(anchor, items) {
    closeMenu();
    menuEl = el('div', { class: 'hbo-theme hbo-menu', role: 'menu' });
    for (const it of items) {
      if (it === 'sep') menuEl.append(el('div', { class: 'hbo-menu-sep', role: 'separator' }));
      else if (it.label && it.header) menuEl.append(el('div', { class: 'hbo-menu-label', text: it.label }));
      else {
        menuEl.append(el('button', {
          type: 'button', role: 'menuitem', class: 'hbo-menu-item' + (it.danger ? ' is-danger' : ''),
          onclick: () => { closeMenu(); it.action(); },
        }, el('span', { class: 'hbo-menu-check', text: it.checked ? '✓' : '' }), it.label));
      }
    }
    document.body.append(menuEl);
    const r = anchor.getBoundingClientRect();
    const m = menuEl.getBoundingClientRect();
    let top = r.bottom + 4;
    if (top + m.height > window.innerHeight - 8) top = Math.max(8, r.top - m.height - 4);
    const left = Math.min(Math.max(8, r.right - m.width), window.innerWidth - m.width - 8);
    menuEl.style.top = top + 'px';
    menuEl.style.left = left + 'px';
    menuEl.querySelector('.hbo-menu-item')?.focus();
    setTimeout(() => {
      document.addEventListener('pointerdown', onMenuOutside, true);
      document.addEventListener('keydown', onMenuKey, true);
      window.addEventListener('scroll', closeMenu, true);
      window.addEventListener('resize', closeMenu);
    });
  }

  function projectMenu(anchor, p) {
    const current = groupFor(p.key);
    const items = [{ label: 'Move to group', header: true }];
    for (const g of config.groups) items.push({ label: g.name, checked: current === g.id, action: () => placeProject(p.key, g.id) });
    items.push({ label: 'Ungrouped', checked: current === UNGROUPED, action: () => placeProject(p.key, UNGROUPED) });
    items.push({ label: 'New group…', action: () => { const g = promptNewGroup(); if (g) placeProject(p.key, g.id); } });
    if (config.assignments[p.key] !== undefined) {
      const ruleGid = groupByRules(p.key);
      const ruleName = ruleGid === UNGROUPED ? 'Ungrouped' : config.groups.find((g) => g.id === ruleGid)?.name;
      items.push('sep', { label: `Follow prefix rules (→ ${ruleName})`, action: () => { delete config.assignments[p.key]; save(); render(); } });
    }
    if (p.children.length) {
      items.push('sep', { label: config.expanded[p.key] ? 'Fold other environments' : 'Show other environments', action: () => toggleProject(p.key) });
    }
    openMenu(anchor, items);
  }

