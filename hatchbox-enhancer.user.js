  let drag = null;       // { type: 'project', key, el } | { type: 'group', gid, el }
  let dropTarget = null; // { gid, beforeKey } | { beforeGid }
  let dropLine = null;

  function clearDropUI() {
    dropLine?.remove();
    dropLine = null;
    S.root?.querySelectorAll('.is-drop-target').forEach((n) => n.classList.remove('is-drop-target'));
  }

  function showLine(parent, before) {
    if (!dropLine) dropLine = el('div', { class: 'hbo-dropline' });
    S.root.querySelectorAll('.is-drop-target').forEach((n) => n.classList.remove('is-drop-target'));
    parent.insertBefore(dropLine, before);
  }

  function nextByMidpoint(items, y) {
    return items.find((n) => { const r = n.getBoundingClientRect(); return y < r.top + r.height / 2; }) || null;
  }

  function wireDnD(root) {
    root.addEventListener('pointerdown', (e) => {
      const grip = e.target.closest('[data-drag]');
      if (!grip) return;
      const target = grip.dataset.drag === 'group' ? grip.closest('.hbo-group') : grip.closest('.hbo-project');
      if (target) target.draggable = true;
    });
    root.addEventListener('pointerup', () => root.querySelectorAll('[draggable="true"]').forEach((n) => { n.draggable = false; }));

    root.addEventListener('dragstart', (e) => {
      const t = e.target;
      if (t.classList?.contains('hbo-project')) drag = { type: 'project', key: t.dataset.key, el: t };
      else if (t.classList?.contains('hbo-group')) drag = { type: 'group', gid: t.dataset.gid, el: t };
      else return;
      closeMenu();
      e.dataTransfer.effectAllowed = 'move';
      e.dataTransfer.setData('text/plain', drag.key || drag.gid);
      requestAnimationFrame(() => drag?.el.classList.add('is-dragging'));
    });

    root.addEventListener('dragover', (e) => {
      if (!drag) return;
      e.preventDefault();
      e.dataTransfer.dropEffect = 'move';
      const y = e.clientY;

      if (drag.type === 'group') {
        const groups = [...root.querySelectorAll(':scope > .hbo-group')].filter((g) => g !== drag.el && g.dataset.gid !== UNGROUPED);
        const before = nextByMidpoint(groups, y);
        const ungrouped = root.querySelector(`:scope > .hbo-group[data-gid="${UNGROUPED}"]`);
        showLine(root, before || ungrouped);
        dropTarget = { beforeGid: before ? before.dataset.gid : null };
        return;
      }

      const group = e.target.closest('.hbo-group');
      if (!group) return;
      const gid = group.dataset.gid;
      if (group.classList.contains('is-collapsed') || e.target.closest('.hbo-ghead')) {
        dropLine?.remove();
        root.querySelectorAll('.is-drop-target').forEach((n) => n.classList.remove('is-drop-target'));
        group.classList.add('is-drop-target');
        dropTarget = { gid, beforeKey: null };
        return;
      }
      const body = group.querySelector('.hbo-gbody');
      const blocks = [...body.querySelectorAll(':scope > .hbo-project')].filter((b) => b !== drag.el);
      const before = nextByMidpoint(blocks, y);
      showLine(body, before);
      dropTarget = { gid, beforeKey: before ? before.dataset.key : null };
    });

    root.addEventListener('drop', (e) => {
      if (!drag || !dropTarget) return;
      e.preventDefault();
      const d = drag;
      const t = dropTarget;
      endDrag();
      if (d.type === 'group') {
        const moving = config.groups.find((g) => g.id === d.gid);
        const rest = config.groups.filter((g) => g.id !== d.gid);
        const at = t.beforeGid ? rest.findIndex((g) => g.id === t.beforeGid) : -1;
        if (at < 0) rest.push(moving); else rest.splice(at, 0, moving);
        config.groups = rest;
        save();
        render();
      } else {
        placeProject(d.key, t.gid, t.beforeKey);
      }
    });

    root.addEventListener('dragend', endDrag);
  }

  function endDrag() {
    if (drag?.el) { drag.el.classList.remove('is-dragging'); drag.el.draggable = false; }
    drag = null;
    dropTarget = null;
    clearDropUI();
  }

