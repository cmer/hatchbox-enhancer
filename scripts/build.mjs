// Builds both distributions from src/ with no dependencies:
//   dist/extension/                       unpacked browser extension (load this in chrome://extensions)
//   dist/hatchbox-enhancer-<v>.zip    upload to the Chrome Web Store (with --zip)
//   hatchbox-enhancer.user.js        userscript, committed so its raw URL can be installed
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const { version, description } = JSON.parse(read('package.json'));

const core = read('src/core.js');
const wrap = (platformFile, factory) =>
  `(function () {\n'use strict';\n\n${core}\n${read(platformFile)}\ncreateOrganizer(${factory}());\n})();\n`;

// Extension
const dist = new URL('dist/', root);
const ext = new URL('dist/extension/', root);
rmSync(dist, { recursive: true, force: true });
mkdirSync(ext, { recursive: true });
const manifest = JSON.parse(read('extension/manifest.json'));
manifest.version = version;
writeFileSync(new URL('manifest.json', ext), JSON.stringify(manifest, null, 2) + '\n');
cpSync(new URL('extension/icons/', root), new URL('icons/', ext), { recursive: true });
writeFileSync(new URL('content.js', ext), `// Hatchbox Enhancer v${version}\n` + wrap('src/platform-extension.js', 'createExtensionPlatform'));

// Userscript
const header = `// ==UserScript==
// @name         Hatchbox Enhancer
// @namespace    hatchbox-enhancer
// @version      ${version}
// @description  ${description}
// @match        https://hatchbox.io/*
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addValueChangeListener
// @grant        GM_xmlhttpRequest
// @connect      api.github.com
// @connect      gist.githubusercontent.com
// @run-at       document-idle
// @license      MIT
// @homepageURL  https://github.com/cmer/hatchbox-enhancer
// @supportURL   https://github.com/cmer/hatchbox-enhancer/issues
// @updateURL    https://raw.githubusercontent.com/cmer/hatchbox-enhancer/main/hatchbox-enhancer.user.js
// @downloadURL  https://raw.githubusercontent.com/cmer/hatchbox-enhancer/main/hatchbox-enhancer.user.js
// ==/UserScript==

// Generated by scripts/build.mjs from src/. Edit the sources, not this file.
`;
writeFileSync(new URL('hatchbox-enhancer.user.js', root), header + wrap('src/platform-userscript.js', 'createUserscriptPlatform'));

if (process.argv.includes('--zip')) {
  const zip = `hatchbox-enhancer-${version}.zip`;
  execFileSync('zip', ['-qr', `../${zip}`, '.'], { cwd: ext });
  console.log(`dist/${zip}`);
}
console.log(`built v${version}: dist/extension/, hatchbox-enhancer.user.js`);
